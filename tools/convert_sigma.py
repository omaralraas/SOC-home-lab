"""Compile the Sigma rules into SIEM queries and write docs/detection-catalog.md.

    python -m tools.convert_sigma            # regenerate the catalog
    python -m tools.convert_sigma --check    # exit 1 if the catalog is stale (CI)

Each rule is converted with pySigma for Splunk (SPL), Elastic (ES|QL, or
Lucene where ES|QL cannot express the rule) and Microsoft Defender XDR /
Sentinel (KQL). Rules are re-parsed for every backend because processing
pipelines rename fields on the rule objects in place.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import yaml
from sigma.backends.elasticsearch import ESQLBackend, LuceneBackend
from sigma.backends.kusto import KustoBackend
from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.conversion.base import Backend
from sigma.exceptions import SigmaError
from sigma.pipelines.elasticsearch.windows import ecs_windows
from sigma.pipelines.microsoftxdr import microsoft_xdr_pipeline
from sigma.pipelines.splunk import splunk_windows_pipeline
from sigma.rule import SigmaRule

REPO_ROOT = Path(__file__).resolve().parents[1]
SIGMA_DIR = REPO_ROOT / "detection-rules" / "sigma"
CASES_DIR = REPO_ROOT / "tests" / "sigma" / "cases"
CATALOG = REPO_ROOT / "docs" / "detection-catalog.md"


@dataclass(frozen=True)
class Target:
    name: str
    language: str  # markdown code-fence language
    backends: tuple[Callable[[], Backend], ...]  # tried in order


TARGETS = (
    Target("Splunk", "spl", (lambda: SplunkBackend(splunk_windows_pipeline()),)),
    Target("Elastic", "sql", (lambda: ESQLBackend(ecs_windows()), lambda: LuceneBackend(ecs_windows()))),
    Target("Microsoft Defender XDR / Sentinel", "kusto", (lambda: KustoBackend(microsoft_xdr_pipeline()),)),
)


@dataclass(frozen=True)
class Conversion:
    ok: bool
    dialect: str  # e.g. "ES|QL" when a target has several dialects
    text: str  # the query, or why no backend could express the rule


def convert(rule_path: Path, target: Target) -> Conversion:
    reason = ""
    for make_backend in target.backends:
        backend = make_backend()
        try:
            collection = SigmaCollection.from_yaml(rule_path.read_text(encoding="utf-8"))
            queries = backend.convert(collection)
        except (SigmaError, NotImplementedError) as exc:
            reason = str(exc).splitlines()[0]
            if "table name" in reason:
                reason = "no table in this schema holds this log source"
            elif "value expressions are not supported" in reason:
                reason = "keyword (full-text) searches are not supported"
            continue
        dialect = {"ESQLBackend": "ES|QL", "LuceneBackend": "Lucene"}.get(type(backend).__name__, "")
        return Conversion(True, dialect, "\n".join(str(q).strip() for q in queries))
    return Conversion(False, "", reason)


def _test_counts() -> dict[str, tuple[int, int]]:
    counts: dict[str, tuple[int, int]] = {}
    for path in sorted(CASES_DIR.glob("*.yml")):
        for rule_id, cases in yaml.safe_load(path.read_text(encoding="utf-8")).items():
            positives = sum(1 for c in cases if c["match"])
            counts[rule_id] = (positives, len(cases) - positives)
    return counts


def _attack_ids(rule: SigmaRule) -> list[str]:
    return [str(t.name).upper() for t in rule.tags if t.namespace == "attack" and t.name.startswith("t")]


def render() -> str:
    paths = sorted(SIGMA_DIR.rglob("*.yml"))
    rules = [(p, SigmaRule.from_yaml(p.read_text(encoding="utf-8"))) for p in paths]
    tests = _test_counts()
    out = [
        "# Detection Catalog",
        "",
        "<!-- Generated by `python -m tools.convert_sigma` from detection-rules/sigma. Do not edit by hand. -->",
        "",
        "Every Sigma rule in this repo, with its ATT&CK mapping, the number of test events it is",
        "checked against in CI (true positives / benign look-alikes), and the query pySigma",
        "compiles it to for each SIEM.",
        "",
        "| Rule | ATT&CK | Level | Tests (TP / benign) |",
        "|---|---|---|---|",
    ]
    for path, rule in rules:
        anchor = path.stem.replace("_", "-")
        tp, fp = tests.get(str(rule.id), (0, 0))
        out.append(f"| [{rule.title}](#{anchor}) | {', '.join(_attack_ids(rule))} | {rule.level} | {tp} / {fp} |")

    for path, rule in rules:
        rel = path.relative_to(REPO_ROOT).as_posix()
        out += [
            "",
            f'<a id="{path.stem.replace("_", "-")}"></a>',
            f"## {rule.title}",
            "",
            f"`{rel}` | ATT&CK {', '.join(_attack_ids(rule))} | level **{rule.level}** | status {rule.status}",
            "",
            str(rule.description).strip(),
        ]
        for target in TARGETS:
            result = convert(path, target)
            heading = f"{target.name} ({result.dialect})" if result.dialect else target.name
            out += ["", f"**{heading}**", ""]
            if result.ok:
                language = "text" if result.dialect == "Lucene" else target.language
                out += [f"```{language}", result.text, "```"]
            else:
                out.append(f"_Not expressible for this backend: {result.text}_")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/detection-catalog.md is out of date")
    args = parser.parse_args(argv)
    rendered = render()
    if args.check:
        current = CATALOG.read_text(encoding="utf-8") if CATALOG.exists() else ""
        if current != rendered:
            print(f"{CATALOG.relative_to(REPO_ROOT)} is stale: run python -m tools.convert_sigma", file=sys.stderr)
            return 1
        return 0
    CATALOG.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {CATALOG.relative_to(REPO_ROOT)} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
